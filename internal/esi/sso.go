// Package esi implements the EVE SSO OAuth2/PKCE login flow and the
// ESI request-forwarding client used by the proxy handler.
package esi

import (
	"context"
	"fmt"
	"sync/atomic"

	"golang.org/x/oauth2"
)

// SSO wraps the OAuth2 PKCE flow against EVE's login server.
type SSO struct {
	cfg oauth2.Config
}

// ClientID returns the EVE SSO client_id this SSO was built with.
func (s *SSO) ClientID() string { return s.cfg.ClientID }

// NewSSO builds an SSO client. redirectURL must match exactly what's
// registered for the application at developers.eveonline.com, and should be
// http://localhost:<port>/sso/callback.
func NewSSO(clientID, ssoBaseURL, redirectURL string, scopes []string) *SSO {
	return &SSO{cfg: oauth2.Config{
		ClientID:    clientID,
		RedirectURL: redirectURL,
		Scopes:      scopes,
		Endpoint: oauth2.Endpoint{
			AuthURL:  ssoBaseURL + "/v2/oauth/authorize",
			TokenURL: ssoBaseURL + "/v2/oauth/token",
		},
	}}
}

// LoginURL builds a PKCE authorization URL. Store verifier server-side
// (keyed by state) so Exchange can be called once the browser redirects back
// to /sso/callback.
func (s *SSO) LoginURL(state string) (url, verifier string) {
	verifier = oauth2.GenerateVerifier()
	url = s.cfg.AuthCodeURL(state, oauth2.S256ChallengeOption(verifier))
	return url, verifier
}

// Exchange trades an authorization code for tokens using the PKCE verifier
// generated by LoginURL.
func (s *SSO) Exchange(ctx context.Context, code, verifier string) (*oauth2.Token, error) {
	tok, err := s.cfg.Exchange(ctx, code, oauth2.VerifierOption(verifier))
	if err != nil {
		return nil, fmt.Errorf("exchange code: %w", err)
	}
	return tok, nil
}

// Refresh exchanges a refresh token for a new access/refresh token pair.
func (s *SSO) Refresh(ctx context.Context, refreshToken string) (*oauth2.Token, error) {
	src := s.cfg.TokenSource(ctx, &oauth2.Token{RefreshToken: refreshToken})
	tok, err := src.Token()
	if err != nil {
		return nil, fmt.Errorf("refresh token: %w", err)
	}
	return tok, nil
}

// SSOHolder makes the active *SSO swappable at runtime — set from the
// management UI when the user enters their EVE client_id, without
// requiring a process restart. Server and tokens.Manager both hold a
// pointer to the same Holder rather than a fixed *SSO, and call Get() at
// each use rather than caching the value.
type SSOHolder struct {
	ptr atomic.Pointer[SSO]
}

func NewSSOHolder(sso *SSO) *SSOHolder {
	h := &SSOHolder{}
	h.ptr.Store(sso)
	return h
}

func (h *SSOHolder) Get() *SSO { return h.ptr.Load() }

func (h *SSOHolder) Set(sso *SSO) { h.ptr.Store(sso) }
